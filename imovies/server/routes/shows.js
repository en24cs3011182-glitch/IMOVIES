const express = require('express');
const { body, param, query } = require('express-validator');
const { protect, authorize } = require('../middleware/auth');
const validateRequest = require('../middleware/validateRequest');
const controller = require('../controllers/showController');

const router = express.Router();
const pageValidation = [
  query('page').optional().isInt({ min: 1 }).toInt(),
  query('limit').optional().isInt({ min: 1 }).toInt(),
];
const idValidation = [param('id').isMongoId().withMessage('Invalid show id')];
const createValidation = [
  body('movie').isMongoId(),
  body('theatre').isMongoId(),
  body('screenId').isMongoId(),
  body('language').isString().trim().notEmpty(),
  body('startTime').isISO8601(),
  body('endTime').isISO8601().custom((endTime, { req }) => new Date(endTime) > new Date(req.body.startTime)),
  body('seats').not().exists().withMessage('Seats are generated by the server'),
  body('priceByType').not().exists().withMessage('Seat prices are configured by the server'),
];
const updateValidation = [
  body('movie').optional().isMongoId(),
  body('theatre').optional().isMongoId(),
  body('screenId').optional().isMongoId(),
  body('language').optional().isString().trim().notEmpty(),
  body('startTime').optional().isISO8601(),
  body('endTime').optional().isISO8601(),
];

router.get('/', pageValidation.concat([
  query('movie').optional().isMongoId(),
  query('city').optional().isString().trim().notEmpty(),
  query('date').optional().isISO8601({ strict: true, strictSeparator: true }),
]), validateRequest, controller.listShows);
router.post('/', protect, authorize('admin'), createValidation, validateRequest, controller.createShow);
router.get('/:id', idValidation, validateRequest, controller.getShow);
router.put('/:id', protect, authorize('admin'), idValidation, updateValidation, validateRequest, controller.updateShow);
router.delete('/:id', protect, authorize('admin'), idValidation, validateRequest, controller.deleteShow);

module.exports = router;
